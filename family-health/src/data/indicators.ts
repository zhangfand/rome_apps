/**
 * The indicator dictionary as reviewable data (see schema.ts for the shape and
 * the validation rules; 指标库 in the app shows all of it).
 *
 * - `legacyRef` holds the ORIGINAL fallback numbers from the first version of
 *   the app. They are NOT verified against any standard (source
 *   `legacy-unverified`, shown as 未核实) and are only used when a report did
 *   not print its own range. Verified candidate ranges go into `ranges` with a
 *   real source; once an indicator has verified ranges, the legacy numbers are
 *   no longer used for it.
 * - `explain` texts are plain-language descriptions written for this app;
 *   they are also `legacy-unverified` until checked.
 * - The first block is the original dictionary converted mechanically; the
 *   second block adds instrument-based items (动脉硬化检测, 心电图, 心脏彩超,
 *   经颅多普勒, 超声骨密度 …) with names and units only.
 *
 * Helpers below only expand left/right variants and aliases; they add no
 * numbers.
 */
import { LEGACY_SOURCE_ID } from "./sources.js";
import type { IndicatorEntryInput } from "./schema.js";
import { VERIFIED_RANGES } from "./verified.js";

type Base = Omit<IndicatorEntryInput, "explain" | "ranges" | "aliases" | "code" | "side"> & { explain: string };

/** A new entry with an unverified plain-language explanation and no ranges yet. */
function entry(e: Omit<IndicatorEntryInput, "explain" | "ranges"> & { explain: string }): IndicatorEntryInput {
  return { ...e, explain: { text: e.explain, sourceId: LEGACY_SOURCE_ID }, ranges: [] };
}

const SIDE_WORDS = { L: ["左", "左侧"], R: ["右", "右侧"] } as const;

/** Side-specific aliases: 左baPWV / 左侧baPWV / baPWV左 / baPWV 左侧 … */
function sideAliases(base: string[], side: "L" | "R", extraPrefixes: string[] = []): string[] {
  const out: string[] = [];
  for (const b of base) {
    for (const w of [...SIDE_WORDS[side], ...extraPrefixes]) out.push(`${w}${b}`, `${b}${w}`);
  }
  return [...new Set(out)];
}

/** Left and right variants of one measurement (codes `<BASE>_L` / `<BASE>_R`). */
function sided(
  codeBase: string,
  spec: Base & { base: string[]; extraPrefixes?: { L: string[]; R: string[] } },
): IndicatorEntryInput[] {
  const { base, extraPrefixes, ...rest } = spec;
  return (["R", "L"] as const).map((side) =>
    entry({
      ...rest,
      code: `${codeBase}_${side}`,
      zh: `${side === "L" ? "左侧" : "右侧"}${spec.zh}`,
      en: `${spec.en} (${side === "L" ? "left" : "right"})`,
      side,
      aliases: sideAliases(base, side, extraPrefixes?.[side]),
    }),
  );
}

/** 经颅多普勒 大脑中动脉 parameter, left and right. */
function tcdMca(param: string, zhParam: string, en: string, unit: string, direction: IndicatorEntryInput["direction"], paramAliases: string[], explain: string) {
  const base = ["大脑中动脉", "MCA"].flatMap((v) => paramAliases.map((p) => `${v}${p}`));
  return sided(`TCD_MCA_${param}`, {
    zh: `大脑中动脉 ${zhParam}`,
    en: `MCA ${en}`,
    category: "tcd",
    unit,
    valueType: "numeric",
    direction,
    decimals: unit === "" ? 2 : 0,
    base,
    explain,
  });
}

